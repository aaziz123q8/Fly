let currentLang = localStorage.getItem('flymasar_lang') || 'ar';

function t(key) {
  return I18N[currentLang][key] || I18N['ar'][key] || key;
}

function setLang(lang) {
  currentLang = lang;
  localStorage.setItem('flymasar_lang', lang);
  document.documentElement.lang = lang;
  document.documentElement.dir = I18N[lang].dir;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (key && I18N[lang][key] !== undefined) {
      el.innerHTML = I18N[lang][key];
    }
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (key && I18N[lang][key] !== undefined) {
      el.placeholder = I18N[lang][key];
    }
  });
  document.querySelectorAll('.lang-btn').forEach(b => {
    b.classList.toggle('active', b.dataset.lang === lang);
  });
  if (window.DatePickerInstances) window.DatePickerInstances.forEach(dp => dp.setLang(lang));
}

function initLang() {
  setLang(currentLang);
}
